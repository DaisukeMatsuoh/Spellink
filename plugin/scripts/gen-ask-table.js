// Generates src/askTable.generated.ts from docs/spec/ask-flow.md. Run: npm run spec
'use strict';
const fs = require('fs');
const path = require('path');
const {parse} = require('./askTable');

const spec = path.join(__dirname, '../../docs/spec/ask-flow.md');
const out = path.join(__dirname, '../src/askTable.generated.ts');
const {states, events, actions, table} = parse(fs.readFileSync(spec, 'utf8'));

const list = a => a.map(x => `'${x}'`).join(', ');
const lit = c => {
  switch (c.k) {
    case 'never':
      return `{k: 'never', note: '${c.note}'}`;
    case 'ignore':
      return c.action ? `{k: 'ignore', action: '${c.action}'}` : `{k: 'ignore', note: '${c.note}'}`;
    case 'do':
      return `{k: 'do', action: '${c.action}', next: '${c.next}'}`;
    default:
      return `{k: 'guard', more: {action: '${c.more.action}', next: '${c.more.next}'}, spent: {action: '${c.spent.action}', next: '${c.spent.next}'}}`;
  }
};
const body = states
  .map(
    s =>
      `  ${s}: {\n${events.map(e => `    ${e}: ${lit(table[s][e])},`).join('\n')}\n  },`,
  )
  .join('\n');

fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-ask-table.js from docs/spec/ask-flow.md — do not edit by hand.
// Change the table in the document, then run \`npm run spec\`.
export const ASK_STATES = [${list(states)}] as const;
export type AskState = (typeof ASK_STATES)[number];
export const ASK_EVENTS = [${list(events)}] as const;
export type AskEvent = (typeof ASK_EVENTS)[number];
export const ASK_ACTIONS = [${list(actions)}] as const;
export type AskAction = (typeof ASK_ACTIONS)[number];

export interface Move {
  action: AskAction;
  next: AskState;
}
/** What happens in one state on one event. */
export type Cell =
  | {k: 'never'; note: string}
  | {k: 'ignore'; note?: string; action?: AskAction}
  | {k: 'do'; action: AskAction; next: AskState}
  | {k: 'guard'; more: Move; spent: Move};

// Typed as a full Record: a missing state or event does not compile.
export const ASK_TABLE: Record<AskState, Record<AskEvent, Cell>> = {
${body}
};
`,
);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${states.length} states x ${events.length} events`);
