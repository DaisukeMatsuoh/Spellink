// Generates src/strings.generated.ts from locales/strings.tsv. Run: npm run strings
//
// The TSV is where the words live: one row per message, one column per language. To add a
// language, add a column. Rules (checked here, and again by __tests__/strings.test.ts):
//   - the first line is `key<TAB>en<TAB>…`; every other language is another column
//   - `\n`, `\t` and `\\` stand for a newline, a tab and a backslash inside a cell
//   - lines starting with `#` and blank lines are ignored
//   - a key is letters and digits, starting with a letter; keys are unique
//   - every `{name}` placeholder of English is in every translation, and no others
//   - an empty cell in a language other than English means "use the English text"
'use strict';
const fs = require('fs');
const path = require('path');

const KEY = /^[a-zA-Z][a-zA-Z0-9]*$/;
const LANG = /^[a-z]{2,3}(_[A-Z]{2})?$/;

function unescape(cell, where) {
  let out = '';
  for (let i = 0; i < cell.length; i++) {
    if (cell[i] !== '\\') {
      out += cell[i];
      continue;
    }
    const n = cell[++i];
    if (n === 'n') out += '\n';
    else if (n === 't') out += '\t';
    else if (n === '\\') out += '\\';
    else throw new Error(`${where}: unknown escape \\${n ?? ''}`);
  }
  return out;
}

const placeholders = text => [...text.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');

/** Parses the TSV text into {languages, keys, table: {lang: {key: text}}}; throws with the line number. */
function parse(tsv) {
  const lines = tsv.split('\n');
  let header = null;
  const keys = [];
  const rows = [];
  lines.forEach((raw, i) => {
    const line = raw.replace(/\r$/, '');
    const where = `line ${i + 1}`;
    if (line === '' || line.startsWith('#')) return;
    const cells = line.split('\t');
    if (!header) {
      if (cells[0] !== 'key' || cells[1] !== 'en') throw new Error(`${where}: the header must start with key<TAB>en`);
      for (const l of cells.slice(1)) if (!LANG.test(l)) throw new Error(`${where}: "${l}" is not a language code`);
      if (new Set(cells).size !== cells.length) throw new Error(`${where}: a language appears twice`);
      header = cells;
      return;
    }
    if (cells.length !== header.length) throw new Error(`${where}: ${cells.length} columns, expected ${header.length}`);
    if (!KEY.test(cells[0])) throw new Error(`${where}: "${cells[0]}" is not a valid key`);
    if (keys.includes(cells[0])) throw new Error(`${where}: key "${cells[0]}" appears twice`);
    keys.push(cells[0]);
    rows.push(cells.map((c, j) => (j === 0 ? c : unescape(c, `${where}, ${header[j]}`))));
  });
  if (!header) throw new Error('no header line');
  const languages = header.slice(1);
  const table = Object.fromEntries(languages.map(l => [l, {}]));
  for (const r of rows) {
    const key = r[0];
    if (r[1] === '') throw new Error(`key "${key}": the English text is required`);
    languages.forEach((l, j) => {
      const text = r[j + 1] === '' ? r[1] : r[j + 1];
      if (placeholders(text) !== placeholders(r[1])) {
        throw new Error(`key "${key}", ${l}: placeholders {${placeholders(text)}} differ from English {${placeholders(r[1])}}`);
      }
      table[l][key] = text;
    });
  }
  return {languages, keys, table};
}

function generate(tsv) {
  const {languages, keys, table} = parse(tsv);
  const lit = s => JSON.stringify(s);
  const body = languages
    .map(l => `  ${lit(l)}: {\n${keys.map(k => `    ${k}: ${lit(table[l][k])},`).join('\n')}\n  },`)
    .join('\n');
  return `// GENERATED by scripts/gen-strings.js from locales/strings.tsv — do not edit by hand.
// Change the words in the TSV, then run \`npm run strings\`.

export const LOCALES = [${languages.map(lit).join(', ')}] as const;

export const STRINGS = {
${body}
} as const;
`;
}

module.exports = {parse, generate};

if (require.main === module) {
  const tsv = fs.readFileSync(path.join(__dirname, '../locales/strings.tsv'), 'utf8');
  fs.writeFileSync(path.join(__dirname, '../src/strings.generated.ts'), generate(tsv));
  const {languages, keys} = parse(tsv);
  console.log(`locales/strings.tsv -> src/strings.generated.ts: ${keys.length} messages, ${languages.join(', ')}`);
}
