// Generates the code tables from the state transition tables in docs/spec. Run: npm run spec
//   ask-flow.md   -> src/askTable.generated.ts
//   wave.md       -> src/waveTable.generated.ts
//   page-turn.md  -> src/insertTable.generated.ts, src/writeTable.generated.ts
//   bridge-run.md -> ../bridge/internal/server/runtable_gen.go
//   pairing.md    -> ../bridge/internal/devices/table_gen.go (record), src/pairTable.generated.ts (device)
'use strict';
const fs = require('fs');
const path = require('path');
const {parse, DEFAULT_SECTIONS} = require('./stmTable');

const spec = f => path.join(__dirname, '../../docs/spec', f);
const rel = f => path.join(__dirname, f);

const PAGE = (t, m) => ({states: `手順（${t}）`, events: '結果', actions: '処理', matrix: `手順表（${t}）`, _: m});
const PAIRING = (side) => ({states: `${side}: 状態`, events: `${side}: イベント`, actions: `${side}: 処理（Action）`, matrix: `${side}: 状態遷移表`});

const SPECS = [
  {md: 'ask-flow.md', out: '../src/askTable.generated.ts', upper: 'ASK', pascal: 'Ask', sections: DEFAULT_SECTIONS},
  {md: 'wave.md', out: '../src/waveTable.generated.ts', upper: 'WAVE', pascal: 'Wave', sections: DEFAULT_SECTIONS},
  {md: 'page-turn.md', out: '../src/insertTable.generated.ts', upper: 'INSERT', pascal: 'Insert', sections: PAGE('挿入')},
  {md: 'page-turn.md', out: '../src/writeTable.generated.ts', upper: 'WRITE', pascal: 'Write', sections: PAGE('書き込み')},
  {md: 'bridge-run.md', out: '../../bridge/internal/server/runtable_gen.go', lang: 'go', sections: DEFAULT_SECTIONS, go: {pkg: 'server', t: 'run', p: 'r'}},
  {md: 'pairing.md', out: '../../bridge/internal/devices/table_gen.go', lang: 'go', sections: PAIRING('記録'), go: {pkg: 'devices', t: 'dev', p: 'd'}},
  {md: 'pairing.md', out: '../src/pairTable.generated.ts', upper: 'PAIR', pascal: 'Pair', sections: PAIRING('端末')},
];

const q = a => a.map(x => `'${x}'`).join(', ');

function ts({upper, pascal}, {states, events, actions, table}, md) {
  const lit = c => {
    switch (c.k) {
      case 'never': return `{k: 'never', note: '${c.note}'}`;
      case 'ignore': return c.action ? `{k: 'ignore', action: '${c.action}'}` : `{k: 'ignore', note: '${c.note}'}`;
      case 'do': return `{k: 'do', action: '${c.action}', next: '${c.next}'}`;
      default: return `{k: 'guard', more: {action: '${c.more.action}', next: '${c.more.next}'}, spent: {action: '${c.spent.action}', next: '${c.spent.next}'}}`;
    }
  };
  const body = states.map(s => `  ${s}: {\n${events.map(e => `    ${e}: ${lit(table[s][e])},`).join('\n')}\n  },`).join('\n');
  return `// GENERATED by scripts/gen-tables.js from docs/spec/${md} — do not edit by hand.
// Change the table in the document, then run \`npm run spec\`.
import type {Table} from './stm';

export const ${upper}_STATES = [${q(states)}] as const;
export type ${pascal}State = (typeof ${upper}_STATES)[number];
export const ${upper}_EVENTS = [${q(events)}] as const;
export type ${pascal}Event = (typeof ${upper}_EVENTS)[number];
export const ${upper}_ACTIONS = [${q(actions)}] as const;
export type ${pascal}Action = (typeof ${upper}_ACTIONS)[number];

// Typed as a full Record: a missing state or event does not compile.
export const ${upper}_TABLE: Table<${pascal}State, ${pascal}Event, ${pascal}Action> = {
${body}
};
`;
}

function go({states, events, actions, table}, md, {pkg, t, p}) {
  // ALL_CAPS names are made CamelCase; a name that already has lower case (Issued, OwnerAdds) is kept as it is
  const id = (p, x) => (/[a-z]/.test(x) ? p + x : p + x[0] + x.slice(1).toLowerCase().replace(/_(.)/g, (_, c) => c.toUpperCase()));
  const st = x => id(`${p}s`, x), ev = x => id(`${p}e`, x), ac = x => `${p}a${x}`;
  const consts = (typ, list, f) => list.map(x => `\t${f(x)} ${typ} = "${x}"`).join('\n');
  const mv = m => `${t}Move{${ac(m.action)}, ${st(m.next)}}`;
  const cell = c => {
    switch (c.k) {
      case 'never': return `{kind: cellNever, note: "${c.note}"}`;
      case 'ignore': return c.action ? `{kind: cellIgnore, action: ${ac(c.action)}}` : `{kind: cellIgnore, note: "${c.note}"}`;
      case 'do': return `{kind: cellDo, action: ${ac(c.action)}, next: ${st(c.next)}}`;
      default: return `{kind: cellGuard, more: ${mv(c.more)}, spent: ${mv(c.spent)}}`;
    }
  };
  const body = states.map(s => `\t${st(s)}: {\n${events.map(e => `\t\t${ev(e)}: ${cell(table[s][e])},`).join('\n')}\n\t},`).join('\n');
  return `// Code generated by scripts/gen-tables.js from docs/spec/${md}. DO NOT EDIT.
// Change the table in the document, then run \`npm run spec\` in plugin/.

package ${pkg}

type ${t}State string

const (
${consts(`${t}State`, states, st)}
)

type ${t}Event string

const (
${consts(`${t}Event`, events, ev)}
)

type ${t}Action string

const (
${consts(`${t}Action`, actions, ac)}
)

const (
	cellNever  = "never"
	cellIgnore = "ignore"
	cellDo     = "do"
	cellGuard  = "guard"
)

type ${t}Move struct {
	action ${t}Action
	next   ${t}State
}

type ${t}Cell struct {
	kind   string
	note   string
	action ${t}Action
	next   ${t}State
	more   ${t}Move
	spent  ${t}Move
}

var ${t}States = []${t}State{${states.map(st).join(', ')}}
var ${t}Events = []${t}Event{${events.map(ev).join(', ')}}
var ${t}Actions = []${t}Action{${actions.map(ac).join(', ')}}

var ${t}Table = map[${t}State]map[${t}Event]${t}Cell{
${body}
}
`;
}

for (const s of SPECS) {
  const md = fs.readFileSync(spec(s.md), 'utf8');
  const parsed = parse(md, s.sections);
  const code = s.lang === 'go' ? go(parsed, s.md, s.go) : ts(s, parsed, s.md);
  fs.writeFileSync(rel(s.out), code);
  console.log(`${s.md} -> ${path.relative(process.cwd(), rel(s.out))}: ${parsed.states.length} x ${parsed.events.length}`);
}
