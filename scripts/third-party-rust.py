#!/usr/bin/env python3
"""Rewrites the Rust section of THIRD_PARTY_NOTICES.md from the lock file (cargo metadata).

    python3 scripts/third-party-rust.py        # run from the repository root

Everything between the two marker lines is replaced; the rest of the file is left alone."""
import collections, json, pathlib, subprocess, sys

START = "<!-- rust-crates:start (generated by scripts/third-party-rust.py; do not edit) -->"
END = "<!-- rust-crates:end -->"
root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root / "bridge", capture_output=True, text=True, check=True).stdout)
crates = sorted({(p["name"], p["version"], p.get("license") or "(see the crate)") for p in meta["packages"] if p["source"]})
by_license = collections.defaultdict(list)
for name, version, lic in crates:
    by_license[lic].append(f"{name} {version}")
lines = [START, "", f"## Bridge, relay and name service (Rust, {len(crates)} crates)", "",
         "The licenses are the ones each crate declares (`cargo metadata`, from `bridge/Cargo.lock`). The full texts and copyright lines are in each crate (crates.io). "
         "Where a crate offers a choice (`MIT OR Apache-2.0`), Spellink uses it under the terms of either. None of them is under a license that requires Spellink's own code to be published under it.", ""]
for lic, items in sorted(by_license.items(), key=lambda kv: (-len(kv[1]), kv[0])):
    lines.append(f"<details><summary>{lic} ({len(items)})</summary>\n\n{', '.join(items)}\n\n</details>\n")
lines += [END]
section = "\n".join(lines)
path = root / "THIRD_PARTY_NOTICES.md"
text = path.read_text()
if START in text:
    a, b = text.index(START), text.index(END) + len(END)
    text = text[:a] + section + text[b:]
else:
    # replace the old (Go) section: from its heading to the line before "The bridge's pairing page"
    a = text.index("## Bridge (Go)")
    b = text.index("The bridge's pairing page")
    text = text[:a] + section + "\n\n" + text[b:]
path.write_text(text)
print(f"{len(crates)} crates, {len(by_license)} license expressions")
